#pragma once

#include <array>
#include <cstdint>

namespace cudasim::exec {

// Each PTX register bank owns a disjoint range in `values`. These are virtual
// register names emitted by NVVM, not physical SM registers. The shared size is
// intentionally larger than the historical 256-entry `r` bank because NVVM can
// emit register indices in the hundreds for unrolled kernels such as `permute`.
// TODO: derive a per-function RegisterLayout from `.reg` declarations instead
// of using fixed 1024-entry banks; see DESIGN.md Section 11 future work.
inline constexpr std::size_t kRegisterBankSize = 1024;
inline constexpr std::size_t kRegisterDBankBase = kRegisterBankSize;
inline constexpr std::size_t kRegisterFBankBase =
    kRegisterDBankBase + kRegisterBankSize;
inline constexpr std::size_t kRegisterSBankBase =
    kRegisterFBankBase + kRegisterBankSize;
inline constexpr std::size_t kRegisterFileSize =
    kRegisterSBankBase + kRegisterBankSize;

struct RegisterFile {
  // PTX register banks are kept in disjoint ranges to avoid collisions:
  //   r<0..N>  -> 0..1023
  //   rd<0..N> -> 1024..2047
  //   f<0..N>  -> 2048..3071
  //   rs<0..N> -> 3072..4095
  // N is bounded by the kernels currently generated by nvcc.
  std::array<std::array<std::uint64_t, 32>, kRegisterFileSize> values{};
  // Predicates are per-lane booleans. 256 is enough for current generated
  // kernels and avoids dynamic allocation in the interpreter hot loop.
  std::array<std::array<bool, 32>, 256> predicates{};
};

} // namespace cudasim::exec
